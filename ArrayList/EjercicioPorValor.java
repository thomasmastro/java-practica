package ArrayList;

public class EjercicioPorValor {

    static void dup(int a){
        a++;
        System.out.println(a);

    }
    public static void main(String[] args) {
        int numeros = 1;
        System.out.println(numeros);
        dup(numeros);
        System.out.println(numeros);
    }
    
}
